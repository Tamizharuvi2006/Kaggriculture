def d1_bugfixed_agent(obs, configuration=None):
    """Arm B: Exact D.1 with Step-696 Early-Return / HIRE Deletion Bug Fixed.

    Preserves the core schedule's valid orders (including HIREs) at Step >= 696
    while merging required terminal liquidation orders, capped at 10 market orders.
    """
    global _APEX35_PRICE_HISTORY
    try:
        step = int(obs.get("step", 0) if isinstance(obs, dict) else getattr(obs, "step", 0) or 0)
        player = int(obs.get("player", 0) if isinstance(obs, dict) else getattr(obs, "player", 0) or 0)
        if step == 0 and "day" in obs:
            step = int(obs.get("day", 0)) * 24 + int(obs.get("hour", 0))
        farms = obs.get("farms") or [] if isinstance(obs, dict) else getattr(obs, "farms", []) or []
        own_farm = farms[player] if len(farms) > player else {}
        money = float(own_farm.get("money", 0.0) or 0.0)
        priv = obs.get("private") or {} if isinstance(obs, dict) else getattr(obs, "private", {}) or {}
        shed = priv.get("shed") or {}
        milk_in_shed = int(shed.get("MILK", 0) or 0)
        fert_in_shed = int(shed.get("FERTILIZER", 0) or 0)
        straw_in_shed = int(shed.get("STRAWBERRY", 0) or 0)
        unlocked = own_farm.get("unlocked_quadrants") or ["NW"]

        market = obs.get("market") or {} if isinstance(obs, dict) else getattr(obs, "market", {}) or {}
        prices = market.get("prices", market.get("current_prices", {})) or {}
        p_straw = float(prices.get("STRAWBERRY", 120.0) or 120.0)
        p_milk = float(prices.get("MILK", 100.0) or 100.0)

        # Call underlying V18 base agent
        act = sub_d1._base_agent(obs)
        if not isinstance(act, dict):
            return {"farmer": ["PASS"], "hands": [], "market": []}

        # Liquidity rescue at step 71
        if step == 71 and money < 1000.0:
            act["market"] = [["SELL", "MILK", milk_in_shed]]
            return act

        market_orders = list(act.get("market") or [])

        # ============================================================================================
        # BUG FIX: End of game clearance (steps >= 696, beginning of Day 30)
        # Preserve core schedule's valid orders (HIREs etc.) and merge required liquidation orders!
        # ============================================================================================
        if step >= 696:
            merged_orders = []
            # First, preserve valid core schedule orders (like HIRE)
            for m in market_orders:
                if isinstance(m, (list, tuple)) and len(m) >= 1:
                    merged_orders.append(m)

            # Then, append any required liquidation sells for remaining shed stock
            if straw_in_shed > 0 and not any(isinstance(m, (list, tuple)) and len(m) >= 2 and m[0] == "SELL" and m[1] == "STRAWBERRY" for m in merged_orders):
                merged_orders.append(["SELL", "STRAWBERRY", straw_in_shed])
            if milk_in_shed > 0 and not any(isinstance(m, (list, tuple)) and len(m) >= 2 and m[0] == "SELL" and m[1] == "MILK" for m in merged_orders):
                merged_orders.append(["SELL", "MILK", milk_in_shed])
            if fert_in_shed > 0 and not any(isinstance(m, (list, tuple)) and len(m) >= 2 and m[0] == "SELL" and m[1] == "FERTILIZER" for m in merged_orders):
                merged_orders.append(["SELL", "FERTILIZER", fert_in_shed])

            act["market"] = merged_orders[:10]
            return act

        # Compute dynamic SAFE_CASH_BUFFER
        if len(unlocked) == 1:
            safe_buffer = 1100.0
        elif len(unlocked) == 2:
            safe_buffer = 2200.0
        else:
            safe_buffer = 400.0

        is_cash_constrained = (money < safe_buffer)

        v_straw = (sub_d1._APEX35_PRICE_HISTORY["STRAWBERRY"][-1] - sub_d1._APEX35_PRICE_HISTORY["STRAWBERRY"][-2]) if len(sub_d1._APEX35_PRICE_HISTORY["STRAWBERRY"]) >= 2 else 0.0
        v_milk = (sub_d1._APEX35_PRICE_HISTORY["MILK"][-1] - sub_d1._APEX35_PRICE_HISTORY["MILK"][-2]) if len(sub_d1._APEX35_PRICE_HISTORY["MILK"]) >= 2 else 0.0

        if is_cash_constrained:
            if straw_in_shed >= 2 and not any(isinstance(m, (list, tuple)) and len(m) >= 2 and m[0] == "SELL" and m[1] == "STRAWBERRY" for m in market_orders):
                market_orders.append(["SELL", "STRAWBERRY", straw_in_shed])
            if milk_in_shed >= 2 and not any(isinstance(m, (list, tuple)) and len(m) >= 2 and m[0] == "SELL" and m[1] == "MILK" for m in market_orders):
                market_orders.append(["SELL", "MILK", milk_in_shed])
        else:
            filtered_orders = []
            for m in market_orders:
                if isinstance(m, (list, tuple)) and len(m) >= 3 and m[0] == "SELL":
                    item = m[1]
                    qty = int(m[2])
                    if item == "STRAWBERRY" and p_straw < 115.0 and v_straw < 0:
                        continue
                    elif item == "MILK" and p_milk < 95.0 and v_milk < 0:
                        continue
                filtered_orders.append(m)

            if p_straw >= 140.0 and straw_in_shed >= 4:
                if not any(isinstance(m, (list, tuple)) and len(m) >= 2 and m[0] == "SELL" and m[1] == "STRAWBERRY" for m in filtered_orders):
                    filtered_orders.append(["SELL", "STRAWBERRY", straw_in_shed])
            if p_milk >= 115.0 and milk_in_shed >= 4:
                if not any(isinstance(m, (list, tuple)) and len(m) >= 2 and m[0] == "SELL" and m[1] == "MILK" for m in filtered_orders):
                    filtered_orders.append(["SELL", "MILK", milk_in_shed])

            market_orders = filtered_orders

        # Enforce 3-quadrant ceiling
        final_orders = []
        for m in market_orders:
            if isinstance(m, (list, tuple)) and len(m) >= 2 and m[0] == "BUY_LAND":
                if len(unlocked) >= 3:
                    continue
            final_orders.append(m)
        act["market"] = final_orders[:10]

        return act
    except Exception:
        return {"farmer": ["PASS"], "hands": [], "market": []}

def run_proof_seed(seed: int = 1000, seat: int = 0):
    print("=" * 115)
    print(f"EXP136 1-SEED PROOF ON SEED {seed} (Seat {seat})")
    print("=" * 115)

    # 1. Run Arm A (Exact D.1 Control)
    env_a = kaggle_environments.make("kaggriculture", configuration={"episodeSteps": 720, "seed": seed})
    env_a.reset()
    p0_w_a = 0
    p0_step696_mkt_a = []

    while not env_a.done:
        step = env_a.state[0].observation.get("step", 0)
        obs0 = env_a.state[0].observation if seat == 0 else env_a.state[1].observation
        obs1 = env_a.state[1].observation if seat == 0 else env_a.state[0].observation

        a0 = sub_d1.agent(obs0, env_a.configuration)
        a1 = bot_v18_mod.agent(obs1)

        if step == 696:
            p0_step696_mkt_a = a0.get("market", [])

        env_a.step([a0, a1] if seat == 0 else [a1, a0])

        if step >= 696:
            f0 = env_a.state[seat].observation["farms"][seat]
            p0_w_a = max(p0_w_a, len(f0.get("workers", [])))

    r_a0 = float(env_a.state[seat].reward or 0.0)
    r_a1 = float(env_a.state[1 - seat].reward or 0.0)

    # 2. Run Arm B (Bug-Fixed D.1)
    env_b = kaggle_environments.make("kaggriculture", configuration={"episodeSteps": 720, "seed": seed})
    env_b.reset()
    p0_w_b = 0
    p0_step696_mkt_b = []

    while not env_b.done:
        step = env_b.state[0].observation.get("step", 0)
        obs0 = env_b.state[0].observation if seat == 0 else env_b.state[1].observation
        obs1 = env_b.state[1].observation if seat == 0 else env_b.state[0].observation

        a0 = d1_bugfixed_agent(obs0, env_b.configuration)
        a1 = bot_v18_mod.agent(obs1)

        if step == 696:
            p0_step696_mkt_b = a0.get("market", [])

        env_b.step([a0, a1] if seat == 0 else [a1, a0])

        if step >= 696:
            f0 = env_b.state[seat].observation["farms"][seat]
            p0_w_b = max(p0_w_b, len(f0.get("workers", [])))

    r_b0 = float(env_b.state[seat].reward or 0.0)
    r_b1 = float(env_b.state[1 - seat].reward or 0.0)

    print(f"\n1. Step-696 Market Orders:")
    print(f"  - Arm A (Original D.1 Bugged) : {p0_step696_mkt_a} (Length: {len(p0_step696_mkt_a)})")
    print(f"  - Arm B (Surgically Bug-Fixed): {p0_step696_mkt_b} (Length: {len(p0_step696_mkt_b)})")

    print(f"\n2. Day-30 Worker Count Spawned:")
    print(f"  - Arm A Workers on Day 30 : {p0_w_a} workers")
    print(f"  - Arm B Workers on Day 30 : {p0_w_b} workers")

    print(f"\n3. Match Result & Wealth:")
    print(f"  - Arm A: D.1=${r_a0:,.0f} vs Opp=${r_a1:,.0f} | Margin=${r_a0-r_a1:+,.0f} | Won={r_a0 > r_a1}")
    print(f"  - Arm B: D.1=${r_b0:,.0f} vs Opp=${r_b1:,.0f} | Margin=${r_b0-r_b1:+,.0f} | Won={r_b0 > r_b1}")
    print(f"  - Delta (Arm B - Arm A): ${r_b0 - r_a0:+,.0f} (Net Gain: ${r_b0 - r_a0:,.0f})")

if __name__ == "__main__":
    run_proof_seed(seed=1000, seat=0)
    run_proof_seed(seed=42, seat=0)
    run_proof_seed(seed=20042, seat=0)
